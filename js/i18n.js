const KEY = "coral-quest-lang";
let lang = "en";
try { const s = localStorage.getItem(KEY); if (s === "en" || s === "id") lang = s; } catch {}
const listeners = new Set();

export const getLang = () => lang;
export const onLang = (fn) => { listeners.add(fn); return () => listeners.delete(fn); };

function resolve(v) { return typeof v === "string" && v.startsWith("@") ? t(v.slice(1)) : v; }

/** Teks polos untuk bahasa aktif */
export function t(key, p) {
  let s = D[lang][key] ?? D.en[key] ?? key;
  if (p) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in p ? resolve(p[k]) : m));
  return s;
}

const escAttr = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

/**
 * Teks yang bisa berganti bahasa: menghasilkan <span data-i18n>.
 * Nilai parameter yang diawali "@" dianggap kunci terjemahan.
 */
export function T(key, p) {
  return `<span data-i18n="${key}"${p ? ` data-p="${escAttr(JSON.stringify(p))}"` : ""}>${t(key, p)}</span>`;
}

function renderAll(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    const p = el.dataset.p ? JSON.parse(el.dataset.p) : undefined;
    el.innerHTML = t(el.dataset.i18n, p);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", el.title);
  });
  document.documentElement.lang = lang;
}

/** Ganti bahasa dengan animasi gelombang */
export function setLang(next, { animate = true } = {}) {
  if (next === lang) return;
  try { localStorage.setItem(KEY, next); } catch {}
  const reduce = window.matchMedia?.("(prefers-reduced-motion: reduce)").matches;
  if (!animate || reduce) { lang = next; renderAll(); listeners.forEach((f) => f(lang)); return; }
  const wave = document.createElement("div");
  wave.className = "lang-wave";
  document.body.appendChild(wave);
  document.body.classList.add("i18n-out");
  setTimeout(() => {
    lang = next;
    renderAll();
    listeners.forEach((f) => f(lang));
    document.body.classList.remove("i18n-out");
    document.body.classList.add("i18n-in");
    setTimeout(() => document.body.classList.remove("i18n-in"), 450);
  }, 260);
  setTimeout(() => wave.remove(), 900);
}

export function initI18n() { renderAll(); }
